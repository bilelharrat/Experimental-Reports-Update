    static func string(_ key: String, lang: AppLanguage) -> String {
        let table: [String: String]
        switch lang {
        case .en: table = en
        case .zh: table = zh
        case .hi: table = hi
        case .es: table = es
        case .fr: table = fr
        case .ar: table = ar
        case .bn: table = bn
        case .pt: table = pt
        case .ru: table = ru
        case .ur: table = ur
        }
        if let val = table[key] { return val }
        if key == "tab.research", let val = table["tab.search"] { return val }
        return en[key] ?? key
    }
